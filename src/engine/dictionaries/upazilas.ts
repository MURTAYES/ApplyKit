/**
 * Returns the list of upazilas for a given district name (English or Bengali).
 */
export function getUpazilasForDistrict(districtName: string): DictionaryEntry[] {
  if (!districtName) return [];
  const normalized = districtName.trim().toLowerCase();

  for (const [distKey, upazilas] of Object.entries(UPAZILAS_BY_DISTRICT)) {
    if (distKey.toLowerCase() === normalized) {
      return upazilas;
    }
  }

  return [];
}
